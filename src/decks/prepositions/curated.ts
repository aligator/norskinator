/** Catches copy-paste slips while editing; a duplicate id would merge two items' SRS history. */
function assertValidItems(items: readonly CuratedItem[]): void {
  const seenIds = new Set<string>();

  for (const item of items) {
    if (seenIds.has(item.id)) {
      throw new Error(`curated.ts: duplicate id "${item.id}"`);
    }

    seenIds.add(item.id);

    const problems: string[] = [];

    if (item.prompt.split('___').length !== 2) {
      problems.push('prompt needs exactly one ___');
    }

    if (!item.options.includes(item.answer)) {
      problems.push('answer missing from options');
    }

    if (new Set(item.options).size !== item.options.length) {
      problems.push('duplicate option');
    }

    if (problems.length > 0) {
      throw new Error(`curated.ts: item "${item.id}": ${problems.join(', ')}`);
    }
  }
}

if (import.meta.env.DEV) {
  assertValidItems(ITEMS);
}

function exerciseId(item: CuratedItem): string {
  return `p-curated-${item.id}`;
}

