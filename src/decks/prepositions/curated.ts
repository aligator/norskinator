/**
 * Hand-written preposition exercises.
 *
 * These carry an explanation and are the backbone of the deck: the corpus
 * items drill recognition, these teach the rule. Keep explanations short and
 * concrete — they are shown right after answering.
 *
 * Every distractor must be clearly wrong in its sentence. Antonyms and
 * near-synonyms that also fit («før/etter jobb», «ved/på sykehuset») do not
 * belong in `options`. `content.test.ts` enforces the mechanical part.
 */
